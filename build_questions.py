Q = []
SEEN = set()


def add(question, options, correct, explanation=""):
    """Savol qo'shadi, dublikatlardan saqlaydi."""
    key = question.strip().lower()
    if key in SEEN:
        return
    if not isinstance(options, list) or len(options) < 2:
        return
    if correct < 0 or correct >= len(options):
        return
    SEEN.add(key)
    Q.append({
        "question": question.strip(),
        "options": options,
        "correct": correct,
        "explanation": explanation,
    })


def add_fact(topic, what, correct_val, wrong_vals, explanation=""):
    """Bitta faktdan savol yaratadi - 4 ta variant bilan."""
    import random
    opts = [correct_val] + list(wrong_vals)
    # 4 ta variantgacha kesib oling
    opts = opts[:4]
    # tasodifiy joylashtirish o'rniga, correct ni 0-3 oraliqda almashtirib turamiz
    idx = (len(SEEN) % 4)
    if idx >= len(opts):
        idx = 0
    # correct ni idx ga ko'chiramiz
    if idx != 0:
        opts[0], opts[idx] = opts[idx], opts[0]
    add(f"{topic} — {what}?", opts, idx, explanation or f"{topic}: {correct_val}")


